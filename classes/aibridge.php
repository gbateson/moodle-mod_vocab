namespace mod_vocab;

use tool_aibridge\library\template;
use tool_aibridge\manager;
use tool_aibridge\provider;

/**
 * The AI providers and prompt library of the AI bridge (tool_aibridge), as
 * the Vocabulary activity uses them.
 *
 * Providers and templates are set up in the bridge, by the site, or by
 * teachers for themselves or their courses. Questions are generated by a
 * background task that runs as the teacher, so teachers' own providers and
 * templates can be used, as well as those shared with them.
 *
 * @package    mod_vocab
 * @copyright  2026 Gordon Bateson
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class aibridge {
    /** No provider: e.g. no images are made. */
    const NONE = 0;

    /** Any provider that the bridge chooses. */
    const AUTOMATIC = -1;

    /** The prefix of the user preferences that hold the defaults for a prompt. */
    const PREFERENCE = 'vocabtool_questionbank_prompt_';

    /** The kinds of media, and the capability that a provider needs to make them. */
    const MEDIA = [
        'image' => provider::CAPABILITY_IMAGE,
        'audio' => provider::CAPABILITY_SPEECH,
        'video' => '',
    ];

    /**
     * Is the AI bridge turned on?
     *
     * @return bool
     */
    public static function is_enabled(): bool {
        return manager::is_enabled();
    }

    /**
     * Get the providers that can generate text, for a menu.
     * The first item is "Automatic", which lets the bridge choose.
     *
     * @param \context $context
     * @param int $userid
     * @return string[] provider id => name.
     */
    public static function get_text_menu(\context $context, int $userid): array {
        $menu = [self::AUTOMATIC => get_string('aibridgeautomatic', 'mod_vocab')];
        $capabilities = [provider::CAPABILITY_TEXT, provider::CAPABILITY_MULTIMODAL];
        foreach (provider::get_available($context, $capabilities, $userid) as $id => $provider) {
            $menu[$id] = $provider->get_name();
        }
        return $menu;
    }

    /**
     * Get the providers that can make a kind of media, for a menu.
     * The first items are "None" and "Automatic".
     *
     * @param string $type image, audio or video.
     * @param \context $context
     * @param int $userid
     * @return string[] provider id => name, or [] if no media of this kind can be made.
     */
    public static function get_media_menu(string $type, \context $context, int $userid): array {
        $capability = isset(self::MEDIA[$type]) ? self::MEDIA[$type] : '';
        if ($capability === '') {
            return [];
        }
        $providers = provider::get_available($context, [$capability], $userid);
        if (empty($providers) && !self::is_core_available($type)) {
            return [];
        }
        $menu = [
            self::NONE => get_string('none'),
            self::AUTOMATIC => get_string('aibridgeautomatic', 'mod_vocab'),
        ];
        foreach ($providers as $id => $provider) {
            $menu[$id] = $provider->get_name();
        }
        return $menu;
    }

    /**
     * Can Moodle's own AI subsystem make this kind of media?
     *
     * @param string $type
     * @return bool
     */
    protected static function is_core_available(string $type): bool {
        if ($type !== 'image') {
            return false;
        }
        return get_config('tool_aibridge', 'coreroute') !== \tool_aibridge\core_bridge::ROUTE_NEVER
            && \tool_aibridge\core_bridge::is_action_available('\\core_ai\\aiactions\\generate_image');
    }

    /**
     * Get the prompts that a user can use, for a menu.
     *
     * @param \context $context
     * @param int $userid
     * @return string[] template id => name.
     */
    public static function get_prompt_menu(\context $context, int $userid): array {
        $menu = [];
        foreach (template::get_available($context, $userid, template::TYPE_PROMPT) as $id => $template) {
            $menu[$id] = format_string($template->get_name());
        }
        return $menu;
    }

    /**
     * Get the output formats that a user can use, for a menu. The first item
     * means "use the format that the prompt links to this question type".
     *
     * @param \context $context
     * @param int $userid
     * @return string[] template id => name.
     */
    public static function get_format_menu(\context $context, int $userid): array {
        $menu = [0 => get_string('aibridgepromptformat', 'mod_vocab')];
        foreach (template::get_available($context, $userid, template::TYPE_FORMAT) as $id => $template) {
            $menu[$id] = format_string($template->get_name());
        }
        return $menu;
    }

    /**
     * Get a template, if it still exists.
     *
     * @param int $id
     * @return template|null
     */
    public static function get_template(int $id): ?template {
        global $DB;
        if ($id <= 0 || !$DB->record_exists(template::TABLE, ['id' => $id])) {
            return null;
        }
        return template::get($id);
    }

    /**
     * Get a provider, if it still exists.
     *
     * @param int $id
     * @return provider|null
     */
    public static function get_provider(int $id): ?provider {
        global $DB;
        if ($id <= 0 || !$DB->record_exists(provider::TABLE, ['id' => $id])) {
            return null;
        }
        return provider::get($id);
    }

    /**
     * Get the question types that a prompt links to output formats. A prompt
     * that links none has the links of the prompt that it extends.
     *
     * @param template $prompt
     * @return string[] question type => format short name.
     */
    public static function get_formatlinks(template $prompt): array {
        $depth = 0;
        while ($prompt && $depth++ < 5) {
            if ($links = $prompt->get_formatlinks()) {
                return $links;
            }
            $prompt = $prompt->get_parent();
        }
        return [];
    }

    /**
     * Get a user's defaults for the question bank form, when a prompt is chosen.
     * If none have been saved, the prompt's question types are ticked.
     *
     * @param template $prompt
     * @param int $userid
     * @return array form field => value.
     */
    public static function get_prompt_defaults(template $prompt, int $userid): array {
        $defaults = json_decode((string) get_user_preferences(self::PREFERENCE . $prompt->get_id(), '', $userid), true);
        if (is_array($defaults)) {
            return $defaults;
        }
        $qtypes = [];
        foreach (array_keys(self::get_formatlinks($prompt)) as $qtype) {
            $qtypes[$qtype] = 0;
        }
        return $qtypes ? ['qtypes' => $qtypes] : [];
    }

    /**
     * Save a user's defaults for the question bank form, for a prompt.
     *
     * @param int $promptid
     * @param array $defaults form field => value.
     * @param int $userid
     */
    public static function save_prompt_defaults(int $promptid, array $defaults, int $userid): void {
        set_user_preference(self::PREFERENCE . $promptid, json_encode($defaults), $userid);
    }

    /**
     * Get the URL of a page of the AI bridge, for a course if the context is in one, else for the site.
     *
     * @param string $page index (providers), library or tunings.
     * @param \context $context
     * @return \moodle_url
     */
    public static function get_url(string $page, \context $context): \moodle_url {
        $coursecontext = $context->get_course_context(false);
        $contextid = $coursecontext ? $coursecontext->id : SYSCONTEXTID;
        return new \moodle_url("/admin/tool/aibridge/$page.php", ['contextid' => $contextid]);
    }
}
